// Generates ../render.yaml (a Render Blueprint) so the security headers keep one source of truth, docker/security-headers.conf.
//   node scripts/render-config.mjs      write ../render.yaml   (npm run render:config)
// web/test/renderConfig.test.ts fails when the committed file differs from what this produces.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const NAMES = { db: 'zenntkaixa-radiozk-db', api: 'zenntkaixa-radiozk-api', web: 'zenntkaixa-radiozk' };
const q = (value) => JSON.stringify(value); // a JSON string is a valid double-quoted YAML scalar

export function buildRenderYaml(headersConf) {
  const security = [...headersConf.matchAll(/^add_header (\S+) "([^"]+)" always;$/gm)].map(([, name, value]) => ({ path: '/*', name, value }));
  const headers = [...security, { path: '/assets/*', name: 'Cache-Control', value: 'public, max-age=31536000, immutable' }]
    .map((h) => `      - path: ${q(h.path)}\n        name: ${h.name}\n        value: ${q(h.value)}`)
    .join('\n');
  const apiUrl = `https://${NAMES.api}.onrender.com`;
  return `# Render Blueprint. GENERATED by web/scripts/render-config.mjs from docker/security-headers.conf:
# edit the script, run \`cd web && npm run render:config\`, commit both. See "Render" in README.md.
#
# The names below are also the onrender.com subdomains. If one is already taken Render appends a suffix, and then
# the /api rewrite destination (and this file) must be updated to the real API URL.
# The database and the API must share a region (it cannot be changed later). Both use the free plan here; a free
# database expires after 30 days and a free web service sleeps when idle (see README.md).

databases:
  - name: ${NAMES.db}
    plan: free
    region: oregon
    databaseName: radiozk
    user: radiozk
    postgresMajorVersion: "18"

services:
  # The API: the Express app from app/, listening on Render's PORT.
  - type: web
    name: ${NAMES.api}
    runtime: node
    plan: free
    region: oregon
    rootDir: app
    buildCommand: npm ci
    startCommand: node src/server.js
    healthCheckPath: /api/health
    envVars:
      - key: DATABASE_URL
        fromDatabase:
          name: ${NAMES.db}
          property: connectionString
      - key: HOST
        value: 0.0.0.0
      - key: TRUST_PROXY
        value: "1"
      - key: NODE_VERSION
        value: 24.22.1

  # The front end: static files on Render's CDN, with /api proxied to the API service.
  - type: web
    name: ${NAMES.web}
    runtime: static
    buildCommand: cd web && npm ci && npm run build
    staticPublishPath: ./www
    envVars:
      - key: NODE_VERSION
        value: 24.22.1
    headers:
${headers}
    routes:
      - type: rewrite
        source: ${q('/api/*')}
        destination: ${q(`${apiUrl}/api/*`)}
      - type: rewrite
        source: ${q('/favicon.ico')}
        destination: ${q('/favicon.svg')}
      - type: rewrite
        source: ${q('/*')}
        destination: ${q('/index.html')}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = new URL('../../', import.meta.url);
  const conf = readFileSync(new URL('docker/security-headers.conf', root), 'utf8');
  writeFileSync(new URL('render.yaml', root), buildRenderYaml(conf));
  console.log('wrote render.yaml');
}
